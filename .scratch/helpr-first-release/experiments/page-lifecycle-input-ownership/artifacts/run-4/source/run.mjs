import {createRequire} from 'node:module';
import {spawn} from 'node:child_process';
import {mkdirSync,readFileSync,writeFileSync,copyFileSync,existsSync} from 'node:fs';
import {createHash} from 'node:crypto';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import net from 'node:net';
const root=path.dirname(fileURLToPath(import.meta.url));
const mode=process.argv[2]||'baseline';
if(!['baseline','diagnostic','candidate'].includes(mode))throw Error('unknown-mode');
const base=root+'/artifacts';mkdirSync(base,{recursive:true});
const registry=base+'/budget.json';
const budget=existsSync(registry)?JSON.parse(readFileSync(registry)):{startedAt:Date.now(),launches:0,cases:0,sourceVersions:[],attempts:[],modelCalls:0,remoteWrites:0};
if(budget.closedAt||budget.launches>=8||Date.now()-budget.startedAt>=3600000)throw Error('experiment-closed-or-budget-exhausted');
const files=['PLAN.md','fixture.html','run.mjs','electron.cjs'];
for(const file of ['ownership.cjs','cases.cjs','native/input-monitor.mm','build.mjs'])if(existsSync(root+'/'+file))files.push(file);
const external={'legacy-native.mm':'../human-input-takeover/native/input-monitor.mm','legacy-native-build.json':'../human-input-takeover/build/metadata.json','control.mjs':'../independent-stop/control.mjs'};
const sha=data=>createHash('sha256').update(data).digest('hex');
const hashes=Object.fromEntries(files.map(file=>[file,sha(readFileSync(root+'/'+file))]));
for(const [name,file]of Object.entries(external))hashes[name]=sha(readFileSync(root+'/'+file));
const version=sha(JSON.stringify(hashes));
if(!budget.sourceVersions.includes(version)){if(budget.sourceVersions.length>=4)throw Error('source-version-budget');budget.sourceVersions.push(version);}
const out=base+'/run-'+(++budget.launches);mkdirSync(out+'/source',{recursive:true});
for(const file of files){mkdirSync(path.dirname(out+'/source/'+file),{recursive:true});copyFileSync(root+'/'+file,out+'/source/'+file);}
for(const [name,file]of Object.entries(external))copyFileSync(root+'/'+file,out+'/source/'+name);
hashes['legacy-native.node']=sha(readFileSync(root+'/../human-input-takeover/build/input-monitor.node'));
if(mode!=='baseline'&&existsSync(root+'/build/input-monitor.node'))hashes['candidate-native.node']=sha(readFileSync(root+'/build/input-monitor.node'));
writeFileSync(out+'/source/hashes.json',JSON.stringify(hashes,null,2)+'\n');
budget.attempts.push({out:path.relative(root,out),mode,startedAt:Date.now(),sourceVersion:version});
writeFileSync(registry,JSON.stringify(budget,null,2)+'\n');
const reserve=net.createServer();await new Promise(resolve=>reserve.listen(0,'127.0.0.1',resolve));const port=reserve.address().port;await new Promise(resolve=>reserve.close(resolve));
const executable=createRequire(new URL('../visible-page-control/package.json',import.meta.url))('electron');
const child=spawn(executable,[root+'/electron.cjs'],{env:{...process.env,LIFECYCLE_OUT:out,LIFECYCLE_MODE:mode,LIFECYCLE_PORT:String(port),LIFECYCLE_BUDGET:registry},stdio:['ignore','pipe','pipe']});
const stdout=[],stderr=[];child.stdout.on('data',chunk=>{stdout.push(chunk);process.stdout.write(chunk);});child.stderr.on('data',chunk=>stderr.push(chunk));
const timer=setTimeout(()=>child.kill('SIGTERM'),120000);
const code=await new Promise(resolve=>child.on('exit',resolve));clearTimeout(timer);
writeFileSync(out+'/stdout.log',Buffer.concat(stdout));writeFileSync(out+'/stderr.log',Buffer.concat(stderr));
const final=JSON.parse(readFileSync(registry));Object.assign(final.attempts.at(-1),{exitCode:code,finishedAt:Date.now()});writeFileSync(registry,JSON.stringify(final,null,2)+'\n');
console.log(JSON.stringify({out,exitCode:code,mode}));process.exitCode=code??1;
